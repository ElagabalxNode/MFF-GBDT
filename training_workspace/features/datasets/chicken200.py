"""
Dataset classes for FusionNet training.

Supports two modes:
1. Legacy mode: Uses internal train_test_split (backward compatible)
2. Aligned mode: Uses external split_info.csv to ensure features and images match

For proper training without data leakage, use aligned mode with split_info.csv
generated by prepare_fusion_split.py.
"""

from torch.utils.data import Dataset
import os
import numpy as np
import pandas as pd
import cv2
from sklearn.model_selection import train_test_split

RANDOM_SEED = 42

def get_project_root():
    """Get project root directory."""
    current_file = os.path.abspath(__file__)
    return os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(current_file))))


def get_default_paths():
    """Return default paths for image data and weight info."""
    project_root = get_project_root()
    return {
        'mask_img_dir': os.path.join(project_root, 'training_workspace', 'data', 'outputs', 'exps', 'data_origin_weight_best_n-result', 'maskImg'),
        'weight_xlsx': os.path.join(project_root, 'training_workspace', 'data', 'raw', 'coco_sets', 'mixData', '20210206-200-weight.xlsx')
    }


def get_existing_images_mapping(mask_img_dir: str) -> dict:
    """
    Build mapping from imgName (CSV format) to actual file path.
    
    Returns dict: imgName -> full_path (only for files that exist)
    """
    mapping = {}
    
    if not os.path.exists(mask_img_dir):
        print(f"Warning: maskImg directory not found: {mask_img_dir}")
        return mapping
    
    for filename in os.listdir(mask_img_dir):
        if not filename.endswith('.png'):
            continue
        
        # Convert filename to imgName format for CSV lookup
        # File: "1.1_Depth-0-0.png" -> CSV: "1.1_Depth-0.png"
        if filename.endswith('-0.png'):
            imgName = filename[:-6] + '.png'
        else:
            imgName = filename
        
        full_path = os.path.join(mask_img_dir, filename)
        mapping[imgName] = full_path
    
    return mapping


def data_split_legacy():
    """
    Legacy split function for backward compatibility.
    Uses internal train_test_split based on image files.
    
    WARNING: This may not align with CSV feature splits!
    """
    paths = get_default_paths()
    dataPath = paths['mask_img_dir']
    xlsxPath = paths['weight_xlsx']
    
    df = pd.read_excel(xlsxPath)

    weightList = []
    nameList = []
    for i in sorted(os.listdir(dataPath)):
        idx = int(i.split('.')[0]) - 1
        weight = df.loc[idx]['体重/kg']
        imgPath = os.path.join(dataPath, i)
        nameList.append(imgPath)
        weightList.append(weight)

    dataset = pd.DataFrame({'path': nameList, 'weight': weightList})

    trainset, testset = train_test_split(dataset, test_size=0.2, random_state=RANDOM_SEED, shuffle=True)
    
    return trainset, testset


def data_split_aligned(split_info_csv: str, mask_img_dir: str = None):
    """
    Aligned split function that uses external split_info.csv.
    
    This ensures images are split exactly the same way as CSV features,
    preventing data leakage. Only includes samples where image files exist.
    
    Args:
        split_info_csv: Path to split_info.csv with columns [imgName, split]
        mask_img_dir: Path to maskImg folder (optional, uses default if None)
    
    Returns:
        trainset, testset: DataFrames with columns [path, weight, imgName]
    """
    if mask_img_dir is None:
        paths = get_default_paths()
        mask_img_dir = paths['mask_img_dir']
    
    # Build mapping of existing images
    img_mapping = get_existing_images_mapping(mask_img_dir)
    print(f"Found {len(img_mapping)} existing images in {mask_img_dir}")
    
    # Load split info
    split_info = pd.read_csv(split_info_csv)
    
    # Load weight info
    paths = get_default_paths()
    xlsxPath = paths['weight_xlsx']
    weight_df = pd.read_excel(xlsxPath)
    
    # Build dataset with proper alignment (only existing images)
    train_data = []
    test_data = []
    skipped = 0
    
    for _, row in split_info.iterrows():
        imgName = row['imgName']  # e.g., "1.1_Depth-0.png"
        split = row['split']      # "train" or "test"
        
        # Skip if image doesn't exist
        if imgName not in img_mapping:
            skipped += 1
            continue
        
        imgPath = img_mapping[imgName]
        
        # Get bird ID to lookup weight
        bird_id = int(imgName.split('.')[0])
        weight = weight_df.loc[bird_id - 1]['体重/kg']
        
        record = {'path': imgPath, 'weight': weight, 'imgName': imgName}
        
        if split == 'train':
            train_data.append(record)
        else:
            test_data.append(record)
    
    trainset = pd.DataFrame(train_data)
    testset = pd.DataFrame(test_data)
    
    if skipped > 0:
        print(f"Skipped {skipped} samples (images not found)")
    print(f"Aligned split loaded: train={len(trainset)}, test={len(testset)}")
    
    return trainset, testset


class ChickenDataset(Dataset):
    """
    Base dataset class for chicken weight estimation.
    
    Args:
        data: DataFrame with columns [path, weight] and optionally [imgName]
        transform: torchvision transforms to apply
    """
    
    def __init__(self, data: pd.DataFrame, transform=None):
        self.imgs = data.reset_index(drop=True)
        self.transform = transform
        
    def __getitem__(self, index):
        row = self.imgs.loc[index]
        x_path = row['path']
        y = row['weight']
        
        img_x = cv2.imread(x_path)
        if img_x is None:
            raise FileNotFoundError(f"Image not found: {x_path}")
            
        if self.transform is not None:
            img_x = self.transform(img_x)
            
        return img_x, y, x_path
        
    def __len__(self):
        return len(self.imgs)


class Chicken_200_trainset(Dataset):
    """
    Train dataset - legacy compatibility wrapper.
    
    For proper training without data leakage, use ChickenDataset with
    data_split_aligned() instead.
    """
    
    def __init__(self, transform=None, split_info_csv=None, mask_img_dir=None):
        """
        Args:
            transform: torchvision transforms
            split_info_csv: Path to split_info.csv for aligned mode (optional)
            mask_img_dir: Path to maskImg folder (optional)
        """
        if split_info_csv is not None:
            # Aligned mode - uses external split
            trainset, _ = data_split_aligned(split_info_csv, mask_img_dir)
        else:
            # Legacy mode
            trainset, _ = data_split_legacy()
            
        self.imgs = trainset.reset_index(drop=True)
        print(f"Train dataset: {len(self.imgs)} samples")
        self.transform = transform

    def __getitem__(self, index):
        row = self.imgs.loc[index]
        x_path = row['path']
        y = row['weight']
        
        img_x = cv2.imread(x_path)
        if img_x is None:
            raise FileNotFoundError(f"Image not found: {x_path}")
            
        if self.transform is not None:
            img_x = self.transform(img_x)
        return img_x, y, x_path

    def __len__(self):
        return len(self.imgs)


